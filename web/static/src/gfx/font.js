/** @type {Map<string, string[]>} */
const GLYPHS = new Map();
for (const line of SOURCE.split("\n")) {
  if (line.length < 3) continue;
  const ch = line[0];
  const rows = line.slice(2).trim().split(/ +/);
  if (rows.length !== 8) throw new Error(`font: ${ch} has ${rows.length} rows`);
  GLYPHS.set(ch, rows);
}

/** Every character the font draws. */
export const FONT_CHARS = [...GLYPHS.keys()].join("");

/** The text colours drawText accepts. */
export const TEXT_COLORS = { dark: UI.dark, light: UI.light };

const glyphCache = memo((key) => {
  const [ch, color] = JSON.parse(key);
  const rows = GLYPHS.get(ch) || GLYPHS.get("?");
  const g = new Grid(8, 8);
  g.stamp(rows, { "#": color }, 1, 0);
  return g.toPixels();
});

/**
 * The 8x8 glyph for a character in the dark text colour; an unknown character draws as '?'.
 * @param {string} ch
 * @param {"dark"|"light"} [color]
 * @returns {Pixels}
 */
export function fontGlyph(ch, color = "dark") {
  return glyphCache(JSON.stringify([ch, TEXT_COLORS[color] || TEXT_COLORS.dark]));
}

/** @param {string} ch */
export function hasGlyph(ch) {
  return GLYPHS.has(ch);
}
